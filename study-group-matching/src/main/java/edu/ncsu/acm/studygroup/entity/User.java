package edu.ncsu.acm.studygroup.entity;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OneToOne;
import jakarta.persistence.PrePersist;
import jakarta.persistence.Table;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

/**
 * Represents a student using the Study Group Matching application.
 * Stores profile information and relationships to courses, preferences,
 * study groups, join requests, and messages.
 */
@Entity
@Table(name = "users")
public class User {

    /**
     * Unique database identifier for the user.
     * The value is automatically generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long userId;

    /**
     * Full name of the student.
     */
    private String name;

    /**
     * Email address associated with the student's account.
     * Each user must have a unique email address.
     */
    @Column(unique = true, nullable = false)
    private String email;

    /**
     * NC State identifier associated with the student.
     * This value is unique when provided.
     */
    @Column(unique = true)
    private String ncsuId;

    /**
     * Academic major of the student.
     */
    private String major;

    /**
     * Academic year of the student, such as freshman, sophomore,
     * junior, or senior.
     */
    private String year;

    /**
     * Short profile description written by the student.
     */
    @Column(length = 1000)
    private String bio;

    /**
     * Stores the location or URL of the student's profile picture.
     */
    private String profilePicture;

    /**
     * Date and time when the user account was created.
     */
    private LocalDateTime createdAt;

    /**
     * Stores all course enrollments belonging to this user.
     * One user can be enrolled in many courses and sections.
     */
    @OneToMany(
            mappedBy = "user",
            cascade = CascadeType.ALL,
            orphanRemoval = true
    )
    private List<Enrollment> enrollments = new ArrayList<>();

    /**
     * Stores the user's overall study preference profile.
     * A user can have at most one StudyPreference object.
     */
    @OneToOne(
            mappedBy = "user",
            cascade = CascadeType.ALL,
            orphanRemoval = true
    )
    private StudyPreference studyPreference;

    /**
     * Stores the study-group memberships belonging to this user.
     * A user can belong to multiple study groups.
     */
    @OneToMany(
            mappedBy = "user",
            cascade = CascadeType.ALL,
            orphanRemoval = true
    )
    private List<GroupMember> groupMemberships = new ArrayList<>();

    /**
     * Stores all requests this user has submitted to join study groups.
     */
    @OneToMany(
            mappedBy = "user",
            cascade = CascadeType.ALL,
            orphanRemoval = true
    )
    private List<JoinRequest> joinRequests = new ArrayList<>();

    /**
     * Stores all chat messages that were sent by this user.
     */
    @OneToMany(
            mappedBy = "sender",
            cascade = CascadeType.ALL
    )
    private List<Message> messages = new ArrayList<>();

    /**
     * Default constructor required by JPA.
     */
    public User() {
    }

    /**
     * Creates a user with the basic information required
     * when initially creating an account.
     *
     * @param name  student's full name
     * @param email student's email address
     */
    public User(final String name, final String email) {
        this.name = name;
        this.email = email;
    }

    /**
     * Automatically records the account creation time
     * immediately before the user is first saved.
     */
    @PrePersist
    protected void onCreate() {
        createdAt = LocalDateTime.now();
    }

    /**
     * Returns the unique identifier for this user.
     *
     * @return user ID
     */
    public Long getUserId() {
        return userId;
    }

    /**
     * Sets the unique identifier for this user.
     *
     * @param userId user ID
     */
    public void setUserId(final Long userId) {
        this.userId = userId;
    }

    /**
     * Returns the student's name.
     *
     * @return student name
     */
    public String getName() {
        return name;
    }

    /**
     * Updates the student's name.
     *
     * @param name new student name
     */
    public void setName(final String name) {
        this.name = name;
    }

    /**
     * Returns the student's email address.
     *
     * @return email address
     */
    public String getEmail() {
        return email;
    }

    /**
     * Updates the student's email address.
     *
     * @param email new email address
     */
    public void setEmail(final String email) {
        this.email = email;
    }

    /**
     * Returns the student's NC State identifier.
     *
     * @return NC State identifier
     */
    public String getNcsuId() {
        return ncsuId;
    }

    /**
     * Updates the student's NC State identifier.
     *
     * @param ncsuId new NC State identifier
     */
    public void setNcsuId(final String ncsuId) {
        this.ncsuId = ncsuId;
    }

    /**
     * Returns the student's academic major.
     *
     * @return academic major
     */
    public String getMajor() {
        return major;
    }

    /**
     * Updates the student's academic major.
     *
     * @param major new academic major
     */
    public void setMajor(final String major) {
        this.major = major;
    }

    /**
     * Returns the student's academic year.
     *
     * @return academic year
     */
    public String getYear() {
        return year;
    }

    /**
     * Updates the student's academic year.
     *
     * @param year new academic year
     */
    public void setYear(final String year) {
        this.year = year;
    }

    /**
     * Returns the student's profile bio.
     *
     * @return profile bio
     */
    public String getBio() {
        return bio;
    }

    /**
     * Updates the student's profile bio.
     *
     * @param bio new profile bio
     */
    public void setBio(final String bio) {
        this.bio = bio;
    }

    /**
     * Returns the student's profile-picture location.
     *
     * @return profile-picture location
     */
    public String getProfilePicture() {
        return profilePicture;
    }

    /**
     * Updates the student's profile-picture location.
     *
     * @param profilePicture new profile-picture location
     */
    public void setProfilePicture(final String profilePicture) {
        this.profilePicture = profilePicture;
    }

    /**
     * Returns the date and time when this account was created.
     *
     * @return account creation time
     */
    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    /**
     * Sets the account creation time.
     *
     * @param createdAt account creation time
     */
    public void setCreatedAt(final LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    /**
     * Returns all course enrollments belonging to this user.
     *
     * @return list of enrollments
     */
    public List<Enrollment> getEnrollments() {
        return enrollments;
    }

    /**
     * Replaces the user's current enrollment list.
     *
     * @param enrollments new enrollment list
     */
    public void setEnrollments(final List<Enrollment> enrollments) {
        this.enrollments = enrollments;
    }

    /**
     * Returns the user's study-preference profile.
     * This corresponds to getPreferences() in the UML.
     *
     * @return study preference
     */
    public StudyPreference getPreferences() {
        return studyPreference;
    }

    /**
     * Updates the user's study-preference profile.
     *
     * @param studyPreference new study preference
     */
    public void setStudyPreference(
            final StudyPreference studyPreference) {
        this.studyPreference = studyPreference;
    }

    /**
     * Returns the user's study-preference profile.
     *
     * @return study preference
     */
    public StudyPreference getStudyPreference() {
        return studyPreference;
    }

    /**
     * Returns all group memberships belonging to this user.
     *
     * @return list of group memberships
     */
    public List<GroupMember> getGroupMemberships() {
        return groupMemberships;
    }

    /**
     * Replaces the user's current group-membership list.
     *
     * @param groupMemberships new membership list
     */
    public void setGroupMemberships(
            final List<GroupMember> groupMemberships) {
        this.groupMemberships = groupMemberships;
    }

    /**
     * Returns all join requests submitted by this user.
     *
     * @return list of join requests
     */
    public List<JoinRequest> getJoinRequests() {
        return joinRequests;
    }

    /**
     * Replaces the user's current join-request list.
     *
     * @param joinRequests new join-request list
     */
    public void setJoinRequests(
            final List<JoinRequest> joinRequests) {
        this.joinRequests = joinRequests;
    }

    /**
     * Returns all chat messages sent by this user.
     *
     * @return list of messages
     */
    public List<Message> getMessages() {
        return messages;
    }

    /**
     * Replaces the user's current message list.
     *
     * @param messages new message list
     */
    public void setMessages(final List<Message> messages) {
        this.messages = messages;
    }

    /**
     * Returns all study groups in which this user is currently
     * registered as a member.
     *
     * @return list of study groups
     */
    public List<StudyGroup> getStudyGroups() {
        return groupMemberships.stream()
                .map(GroupMember::getStudyGroup)
                .toList();
    }

    /**
     * Updates the editable profile information belonging to this user.
     *
     * @param name           updated name
     * @param major          updated major
     * @param year           updated academic year
     * @param bio            updated profile bio
     * @param profilePicture updated profile-picture location
     */
    public void updateProfile(final String name,
                              final String major,
                              final String year,
                              final String bio,
                              final String profilePicture) {
        this.name = name;
        this.major = major;
        this.year = year;
        this.bio = bio;
        this.profilePicture = profilePicture;
    }

    /**
     * Adds a course and section to the user's enrollment list.
     * More detailed validation can later be handled by the service layer.
     *
     * @param course  course being added
     * @param section section being added
     */
    public void addCourse(final Course course,
                          final Section section) {
        final Enrollment enrollment =
                new Enrollment(this, course, section);

        enrollments.add(enrollment);
    }

    /**
     * Removes the user's enrollment for the specified course.
     *
     * @param course course to remove
     */
    public void removeCourse(final Course course) {
        enrollments.removeIf(
                enrollment -> enrollment.getCourse().equals(course)
        );
    }
}